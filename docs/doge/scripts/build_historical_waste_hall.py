def cost_score(eur: float | None) -> float:
    if eur is None or eur <= 0:
        return 0.0
    if eur < 1e6:
        return 1.5
    if eur < 1e7:
        return 3.5
    if eur < 1e8:
        return 5.5
    if eur < 1e9:
        return 7.5
    return 9.5


def pain(c: float | None) -> dict[str, str]:
    if c is None:
        return {
            "pain_tax_fte": "",
            "pain_net_years": "",
            "pain_eur_per_employee": "",
            "pain_work_minutes": "",
        }
    return {
        "pain_tax_fte": f"{c / TAX:.1f}",
        "pain_net_years": f"{c / NET:.1f}",
        "pain_eur_per_employee": f"{c / N_EMP:.2f}",
        "pain_work_minutes": f"{c / N_EMP / EUR_PER_MIN:.2f}",
    }


def fmt_eur(n: float | None) -> str:
    if n is None:
        return "Unknown"
    if n >= 1e9:
        return f"€{n/1e9:.2f} bn"
    if n >= 1e6:
        return f"€{n/1e6:.1f} m"
    if n >= 1e3:
        return f"€{n/1e3:.0f} k"
    return f"€{n:.0f}"


def fmt_min(m: str) -> str:
    if not m:
        return "—"
    x = float(m)
    if abs(x) >= 60:
        h = x / 60
        if h >= 24:
            return f"{x:.0f} min (~{h/24:.1f} d)"
        return f"{x:.0f} min (~{h:.1f} h)"
    if abs(x) >= 1:
        return f"{x:.1f} min"
    return f"{x:.2f} min"


