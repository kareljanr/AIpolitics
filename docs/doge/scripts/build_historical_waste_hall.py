def main() -> int:
    rows = []
    for t in RAW:
        (
            _id,
            name,
            era,
            level,
            typ,
            category,
            cmin,
            cmid,
            cmax,
            basis,
            absu,
            purity,
            conf,
            sources,
            one_liner,
            notes,
        ) = t
        cs = cost_score(cmid)
        # waste_priority: cost + absurdity + purity (how 'pure waste' vs mixed public good)
        prio = round(0.45 * cs + 0.30 * absu + 0.25 * purity, 2)
        p = pain(cmid)
        rows.append(
            {
                "item_id": _id,
                "name": name,
                "era": era,
                "level": level,
                "type": typ,
                "category": category,
                "cost_min_eur": f"{cmin:.0f}" if cmin is not None else "",
                "cost_mid_eur": f"{cmid:.0f}" if cmid is not None else "",
                "cost_max_eur": f"{cmax:.0f}" if cmax is not None else "",
                "cost_basis": basis,
                "cost_score": f"{cs:.1f}",
                "absurdity_score": f"{absu:.1f}",
                "waste_purity": f"{purity:.1f}",
                "waste_priority": f"{prio:.2f}",
                "confidence": conf,
                **p,
                "sources_brief": sources,
                "one_liner": one_liner,
                "notes": notes,
            }
        )

    rows.sort(key=lambda r: (-float(r["waste_priority"]), -float(r["cost_mid_eur"] or 0)))
    for i, r in enumerate(rows, 1):
        r["rank"] = str(i)

    fields = [
        "rank",
        "item_id",
        "name",
        "era",
        "level",
        "type",
        "category",
        "cost_min_eur",
        "cost_mid_eur",
        "cost_max_eur",
        "cost_basis",
        "cost_score",
        "absurdity_score",
        "waste_purity",
        "waste_priority",
        "confidence",
        "pain_tax_fte",
        "pain_net_years",
        "pain_eur_per_employee",
        "pain_work_minutes",
        "sources_brief",
        "one_liner",
        "notes",
    ]
    DATA.mkdir(parents=True, exist_ok=True)
    with OUT_CSV.open("w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader()
        w.writerows(rows)

    write_md(rows)
    print(f"Wrote {len(rows)} rows → {OUT_CSV}")
    print(f"Wrote markdown → {OUT_MD}")
    return 0


